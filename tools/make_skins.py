# The rail takes the text face, narrow enough for its labels; these skins'
# display faces are condensed enough to wear there too.
NAV_DISPLAY = {"starliner": True}


def font_faces():
    rules = []
    for family, files in FONTS.items():
        for file, weight in files:
            rules.append(f'@font-face {{ font-family: "{family}"; font-weight: {weight}; font-display: swap; '
                         f'src: url("../fonts/{file}") format("truetype"); }}')
    return "\n".join(rules)


def tokens():
    rules = []
    for skin, (text, display, case, track, card, control) in SKINS.items():
        rules.append(f':root[data-skin="{skin}"] {{ --skin-text: "{text}", "Segoe UI", sans-serif; '
                     f'--skin-display: "{display}", "{text}", sans-serif; --skin-case: {case}; --skin-track: {track}; '
                     f'--skin-card-radius: {card}; --skin-control-radius: {control}; '
                     f'--skin-nav: {NAV_DISPLAY.get(skin) and f"var(--skin-display)" or "var(--skin-text)"}; }}')
    return "\n".join(rules)


